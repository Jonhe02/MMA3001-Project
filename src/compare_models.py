"""Compare YOLO11n and YOLO11s evaluation summaries from the same dataset.

Examples (run from the project root):
    python src/compare_models.py --dataset 4
    python src/compare_models.py --dataset 4 --split val
    python src/compare_models.py --dataset 4 --n-run yolo11n_2class_v2 --s-run yolo11s_2class_v2

Requires evaluation_summary.json files generated by src/evaluate.py.
Writes a comparison CSV to results/model_comparison/.
"""

import argparse
import csv
import json
from datetime import datetime, timezone
from pathlib import Path

from experiment_config import DATASETS, PROJECT_ROOT, RUNS_DIR


METRICS = (
    ("precision", "Precision", "higher"),
    ("recall", "Recall", "higher"),
    ("map50", "mAP50", "higher"),
    ("map50_95", "mAP50-95", "higher"),
    ("inference_ms", "Inference time (ms/image)", "lower"),
)


def matches_training_run(name: str, base: str) -> bool:
    """Accept a base run or a numbered rerun (e.g. ..._run2)."""
    if name == base:
        return True
    suffix = name.removeprefix(base + "_run")
    return name.startswith(base + "_run") and suffix.isdigit()


def load_summary(path: Path) -> dict:
    """Parse a saved evaluation summary with a useful error message."""
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        raise ValueError(f"Cannot read JSON file: {path}: {exc}") from exc
    if not isinstance(data, dict):
        raise ValueError(f"Expected a JSON object in {path}")
    return data


def choose_summary(dataset: int, slug: str, model_size: str,
                   split: str, requested_run: str | None) -> tuple[Path, dict]:
    """Select the newest matching summary, or one from an explicit training run."""
    base = f"yolo11{model_size}_{slug}"
    matches = []
    for path in RUNS_DIR.rglob("evaluation_summary.json") if RUNS_DIR.is_dir() else []:
        info = load_summary(path)
        run = str(info.get("training_run", ""))
        if (info.get("dataset_number") != dataset
                or info.get("model") != f"yolo11{model_size}"
                or info.get("evaluation_split") != split
                or not matches_training_run(run, base)):
            continue
        if requested_run is not None and requested_run != run:
            continue
        # The timestamp comes from evaluate.py; file mtime is a fallback.
        try:
            created = datetime.fromisoformat(info["created_at_utc"].replace("Z", "+00:00"))
            if created.tzinfo is None:
                created = created.replace(tzinfo=timezone.utc)
            timestamp = created.timestamp()
        except (KeyError, ValueError, TypeError):
            timestamp = path.stat().st_mtime
        matches.append((timestamp, path, info))

    if not matches:
        run_hint = f" for training run '{requested_run}'" if requested_run else ""
        raise FileNotFoundError(
            f"No saved {split} evaluation of {base}{run_hint} found in {RUNS_DIR}.\n"
            f"Run: python src/evaluate.py --dataset {dataset} --model {model_size} --split {split}"
            + (f" --run {requested_run}" if requested_run else "")
        )
    _, path, info = max(matches, key=lambda item: (item[0], str(item[1])))
    return path, info


def metric_value(info: dict, key: str) -> float:
    """Read an overall metric from the JSON created by evaluate.py."""
    if key == "inference_ms":
        raw = info.get("speed_ms_per_image", {}).get("inference")
    else:
        raw = info.get(key)
    if raw is None:
        raise ValueError(f"Evaluation JSON is missing '{key}'. Re-run evaluate.py.")
    return float(raw)


def main() -> None:
    """Print a model comparison and export it as a CSV file."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--dataset", type=int, choices=sorted(DATASETS), default=4)
    parser.add_argument("--split", choices=("val", "test"), default="val")
    parser.add_argument("--n-run", help="Optional exact YOLO11n training run folder name")
    parser.add_argument("--s-run", help="Optional exact YOLO11s training run folder name")
    args = parser.parse_args()

    _, slug, _ = DATASETS[args.dataset]
    n_path, n_info = choose_summary(args.dataset, slug, "n", args.split, args.n_run)
    s_path, s_info = choose_summary(args.dataset, slug, "s", args.split, args.s_run)

    print(f"Dataset {args.dataset} ({slug}), split: {args.split}")
    print(f"YOLO11n: {n_info['training_run']} -> {n_path}")
    print(f"YOLO11s: {s_info['training_run']} -> {s_path}")
    print("\nMetric                        YOLO11n      YOLO11s      s - n    Better")
    print("-" * 80)

    rows = []
    for key, display, preferred in METRICS:
        n_value = metric_value(n_info, key)
        s_value = metric_value(s_info, key)
        delta = s_value - n_value
        if abs(delta) < 1e-12:
            better = "tie"
        elif (delta > 0) == (preferred == "higher"):
            better = "YOLO11s"
        else:
            better = "YOLO11n"
        rows.append((display, round(n_value, 6), round(s_value, 6), round(delta, 6), better))
        print(f"{display:<29} {n_value:>9.4f}    {s_value:>9.4f}    {delta:>8.4f}    {better}")

    output_dir = PROJECT_ROOT / "results" / "model_comparison"
    output_dir.mkdir(parents=True, exist_ok=True)
    output_file = output_dir / f"{slug}_{args.split}_comparison.csv"
    with output_file.open("w", newline="", encoding="utf-8-sig") as stream:
        writer = csv.writer(stream)
        writer.writerow(("metric", "yolo11n", "yolo11s", "s_minus_n", "better"))
        writer.writerows(rows)

    # Record exactly which results were compared for reproducibility.
    source_file = output_dir / f"{slug}_{args.split}_comparison_sources.json"
    source_file.write_text(
        json.dumps({
            "dataset_number": args.dataset,
            "split": args.split,
            "yolo11n_training_run": n_info["training_run"],
            "yolo11n_evaluation_json": str(n_path.relative_to(PROJECT_ROOT)),
            "yolo11s_training_run": s_info["training_run"],
            "yolo11s_evaluation_json": str(s_path.relative_to(PROJECT_ROOT)),
        }, indent=2) + "\n", encoding="utf-8"
    )
    print(f"\nComparison saved to: {output_file}")
    print(f"Source records saved to: {source_file}")
    print("Note: These summaries do not include per-class AP or training duration.")


if __name__ == "__main__":
    main()
